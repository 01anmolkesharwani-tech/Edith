/**
 * Mail transports. Credentials are read from server-side environment variables only;
 * they are never stored in the database, sent to the browser, or logged.
 */
import nodemailer from "nodemailer";

export interface OutgoingMessage {
  from: { name: string; address: string };
  to: { name?: string | null; address: string };
  subject: string;
  text: string;
  messageId: string; // generated by us so the send can be traced even on ambiguous failures
  inReplyTo?: string | null;
  references?: string[];
  attachment?: { filename: string; content: Buffer; contentType: string } | null;
}

export interface TransportResult {
  accepted: string[];
  rejected: string[];
  messageId: string;
  response: string;
}

export interface MailTransport {
  readonly kind: string;
  send(msg: OutgoingMessage): Promise<TransportResult>;
  verify?(): Promise<void>;
}

export interface SmtpAccountConfig {
  smtpHost: string | null;
  smtpPort: number | null;
  smtpSecure: boolean;
  smtpUser: string | null;
  secretEnvVar: string | null;
}

export class TransportConfigError extends Error {}

export function readSecret(envVar: string | null): string | null {
  if (!envVar || !/^[A-Z][A-Z0-9_]{2,63}$/.test(envVar)) return null;
  const v = process.env[envVar];
  return v && v.length ? v : null;
}

export function smtpTransport(cfg: SmtpAccountConfig): MailTransport {
  if (!cfg.smtpHost || !cfg.smtpPort || !cfg.smtpUser) throw new TransportConfigError("SMTP host, port and username are required.");
  const pass = readSecret(cfg.secretEnvVar);
  if (!pass) throw new TransportConfigError(`The environment variable ${cfg.secretEnvVar ?? "(not set)"} is missing on the server.`);
  const t = nodemailer.createTransport({
    host: cfg.smtpHost,
    port: cfg.smtpPort,
    secure: cfg.smtpSecure,
    requireTLS: !cfg.smtpSecure,
    auth: { user: cfg.smtpUser, pass },
    connectionTimeout: 15_000,
    greetingTimeout: 15_000,
    socketTimeout: 60_000,
    logger: false,
    debug: false,
  });
  return {
    kind: "SMTP",
    async send(msg) {
      const info = await t.sendMail({
        from: { name: msg.from.name, address: msg.from.address },
        to: msg.to.name ? { name: msg.to.name, address: msg.to.address } : msg.to.address,
        subject: msg.subject,
        text: msg.text,
        messageId: msg.messageId,
        inReplyTo: msg.inReplyTo ?? undefined,
        references: msg.references?.length ? msg.references : undefined,
        attachments: msg.attachment ? [msg.attachment] : [],
      });
      return {
        accepted: addressList(info.accepted),
        rejected: addressList(info.rejected),
        messageId: info.messageId ?? msg.messageId,
        response: String(info.response ?? "").slice(0, 300),
      };
    },
    async verify() {
      await t.verify();
    },
  };
}

function addressList(list: unknown): string[] {
  if (!Array.isArray(list)) return [];
  return list.map((a) => (typeof a === "string" ? a : String((a as { address?: string }).address ?? ""))).map((a) => a.toLowerCase());
}

/**
 * Classify a transport error. Returns "FAILED" when the provider definitely did not accept
 * the message (safe to let the user retry later) and "UNKNOWN" when it might have been
 * accepted (e.g. a timeout after data was transmitted) — never auto-retried.
 */
export function classifySendError(err: unknown): { outcome: "FAILED" | "UNKNOWN"; message: string } {
  const e = err as { code?: string; responseCode?: number; command?: string; message?: string };
  const message = (e.message ?? "Send failed").replace(/(pass(word)?|auth)[^\s]*\s*[:=]\s*\S+/gi, "$1=[redacted]").slice(0, 300);
  if (typeof e.responseCode === "number") return { outcome: "FAILED", message: `Server replied ${e.responseCode}: ${message}` };
  const definite = ["EAUTH", "EENVELOPE", "EDNS", "ECONNECTION", "ETLS", "ECONFIG", "EMESSAGE", "ENOTFOUND", "ECONNREFUSED"];
  if (e.code && definite.includes(e.code)) return { outcome: "FAILED", message };
  if (e.command === "CONN" || e.command === "EHLO" || e.command === "AUTH PLAIN" || e.command === "AUTH LOGIN" || e.command === "MAIL FROM" || e.command === "RCPT TO") {
    return { outcome: "FAILED", message };
  }
  return { outcome: "UNKNOWN", message: `Outcome unknown (${e.code ?? "error"}): ${message}` };
}
